# Step 2: Load Book Metadata
# ==============================================================================
def load_metadata_from_db(db_path):
    """Load book metadata from SQLite and format document text."""
    print(f"\n[Metadata] Loading from {db_path.name}...")
    t0 = time.time()
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()

    book_texts = {}
    title_of = {}
    base_title_of = {}
    sig_words_of = {}
    series_of = {}
    work_id_of = {}

    query = "SELECT book_id, title, authors, description, popular_shelves FROM books"
    for row in cur.execute(query):
        bid = str(row[0])
        title = row[1] or ""
        desc = (row[3] or "").strip()
        shelves_raw = row[4] or "[]"

        # Format book text: Title | Genres | Description
        parts = []
        if title.strip():
            parts.append(f"Title: {title.strip()}")
        try:
            shelf_list = json.loads(shelves_raw)
            if shelf_list:
                parts.append(f"Genres: {', '.join(shelf_list)}")
        except Exception:
            shelf_list = []
        if desc:
            parts.append(f"Description: {desc[:900]}")
        book_texts[bid] = " | ".join(parts) if parts else "Untitled"

        # Metadata for false-negative prevention
        title_of[bid] = norm(title)
        base_title_of[bid] = extract_base_title(title)
        sig_words_of[bid] = get_significant_words(title)
        series_of[bid] = extract_series_name(title)

    conn.close()
    print(f"[Metadata] Loaded {len(book_texts):,} books in {time.time() - t0:.2f}s.")
    return {
        "book_texts": book_texts,
        "title_of": title_of,
        "base_title_of": base_title_of,
        "sig_words_of": sig_words_of,
        "series_of": series_of,
    }


# ==============================================================================
# Step 3: Work-Cluster Split (Edition-Safe)
# ==============================================================================
def build_work_clusters(records, meta):
    """Group books by work_id (or title fallback) to prevent edition leakage."""
    clusters = defaultdict(list)
    for r in records:
        bid = str(r["book_id"])
        # Use work_id if available, otherwise fall back to normalized title
        key = "t:" + norm(r["title"])  # Default: title-based clustering
        clusters[key].append(bid)

    cluster_of = {b: k for k, v in clusters.items() for b in v}
    multi = sum(1 for v in clusters.values() if len(v) > 1)
    print(f"[Split] Work clusters: {len(clusters):,} ({multi:,} multi-edition)")
    return clusters, cluster_of


def split_by_clusters(clusters, train_ratio=0.8, val_ratio=0.1, seed=42):
    """Split cluster keys into train/val/test sets."""
    keys = sorted(clusters)
    random.Random(seed).shuffle(keys)
    n = len(keys)
    train_keys = set(keys[:int(n * train_ratio)])
    val_keys = set(keys[int(n * train_ratio):int(n * (train_ratio + val_ratio))])
    test_keys = set(keys[int(n * (train_ratio + val_ratio)):])
    return train_keys, val_keys, test_keys


# ==============================================================================
# Step 4: Embed Catalog for Hard-Negative Mining
# ==============================================================================
def embed_catalog(model, meta, all_book_ids):
    """Encode the full book catalog into normalized embeddings."""
    import torch

    if CATALOG_EMB_FILE.exists() and CATALOG_IDS_FILE.exists():
        cached_ids = json.load(open(CATALOG_IDS_FILE))
        if cached_ids == all_book_ids:
            print("[Embed] Using cached catalog embeddings.")
            return np.load(CATALOG_EMB_FILE)

    print(f"[Embed] Encoding {len(all_book_ids):,} books...")
    t0 = time.time()
    texts = [meta["book_texts"][b] for b in all_book_ids]

    EMB_CACHE_DIR.mkdir(exist_ok=True)
    chunk_size = 1000
    n_chunks = (len(texts) + chunk_size - 1) // chunk_size
    chunks = []

    for ci in range(n_chunks):
        lo = ci * chunk_size
        hi = min(len(texts), (ci + 1) * chunk_size)
        cache_path = EMB_CACHE_DIR / f"emb_{ci:04d}.npy"
        if cache_path.exists():
            chunks.append(np.load(cache_path))
        else:
            with torch.no_grad():
                e = model.encode(
                    texts[lo:hi],
                    batch_size=EMBED_BATCH_SIZE,
                    normalize_embeddings=True,
                    convert_to_numpy=True,
                    show_progress_bar=False,
                ).astype("float32")
            np.save(cache_path, e)
            chunks.append(e)
        if (ci + 1) % 10 == 0 or ci + 1 == n_chunks:
            elapsed = time.time() - t0
            print(f"  Chunk {ci+1}/{n_chunks} | {hi:,}/{len(texts):,} books | {elapsed:.1f}s")

    embs = np.concatenate(chunks)
    np.save(CATALOG_EMB_FILE, embs)
    json.dump(all_book_ids, open(CATALOG_IDS_FILE, "w"))
    print(f"[Embed] Catalog embedded: {embs.shape} in {time.time() - t0:.1f}s")
    return embs


# ==============================================================================
# Step 5: Hard-Negative Mining with False-Negative Protection
# ==============================================================================
def is_false_negative(pos_id, cand_id, cand_score, meta, banned_ids):
    """Multi-layer check to prevent labelling related books as negatives."""
    if cand_id in banned_ids:
        return True, "banned_id"
    if cand_score > MAX_COSINE_SIM:
        return True, "cosine_ceiling"

    # Identical normalized title
    pos_title = meta["title_of"].get(pos_id, "")
    cand_title = meta["title_of"].get(cand_id, "")
    if pos_title and cand_title and pos_title == cand_title:
        return True, "identical_title"

    # Base title match (stripping subtitles/editions)
    pos_base = meta["base_title_of"].get(pos_id, "")
    cand_base = meta["base_title_of"].get(cand_id, "")
    if pos_base and cand_base and pos_base == cand_base and len(pos_base) > 3:
        return True, "base_title_match"

    # Significant title word overlap
    pos_words = meta["sig_words_of"].get(pos_id, set())
    cand_words = meta["sig_words_of"].get(cand_id, set())
    if pos_words and cand_words:
        shared = pos_words & cand_words
        min_len = min(len(pos_words), len(cand_words))
        if min_len >= 2 and (len(shared) / min_len) >= 0.65:
            return True, "title_word_overlap"

    # Series match
    pos_series = meta["series_of"].get(pos_id, "")
    cand_series = meta["series_of"].get(cand_id, "")
    if pos_series and cand_series and pos_series == cand_series:
        return True, "series_match"

    return False, ""


def mine_hard_negatives(records, meta, all_book_ids, catalog_embs, model, cluster_of,
                        train_keys, val_keys, test_keys):
    """Mine hard negatives and write train/val/test splits."""
    import torch

    print("\n" + "=" * 70)
    print("  STEP 5: HARD-NEGATIVE MINING")
    print("=" * 70)

    bidx = {b: i for i, b in enumerate(all_book_ids)}

    # Index cross-query positives
    query_positives = defaultdict(set)
    for r in records:
        for q in r["queries"]:
            query_positives[norm(q)].add(str(r["book_id"]))

    def split_of(bid):
        cl = cluster_of.get(bid, "")
        if cl in train_keys:
            return "train"
        elif cl in val_keys:
            return "val"
        return "test"

    # Build all (book_id, query) pairs
    rows = []
    for r in records:
        bid = str(r["book_id"])
        if bid not in bidx:
            continue
        for q in r["queries"]:
            rows.append((bid, q))

    print(f"  Total query-book pairs: {len(rows):,}")

    # Encode all queries
    print("  Encoding queries...")
    q_texts = [QUERY_INSTRUCTION + q for _, q in rows]
    q_embs_chunks = []
    q_chunk_size = 20000
    t0 = time.time()
    for ci in range(0, len(q_texts), q_chunk_size):
        chunk = q_texts[ci:ci + q_chunk_size]
        with torch.no_grad():
            e = model.encode(
                chunk,
                batch_size=512,
                normalize_embeddings=True,
                convert_to_numpy=True,
                show_progress_bar=False,
            ).astype("float32")
        q_embs_chunks.append(e)
        print(f"    Query chunk: {min(ci + q_chunk_size, len(q_texts)):,}/{len(q_texts):,}")
    q_embs = np.concatenate(q_embs_chunks)
    print(f"  Queries encoded: {q_embs.shape} in {time.time() - t0:.1f}s")

    # Mine negatives in chunks
    outs = {s: open(BASE_DIR / f"{s}.jsonl", "w", encoding="utf-8")
            for s in ("train", "val", "test")}
    stats = defaultdict(lambda: defaultdict(int))
    blocked = Counter()

    for lo in range(0, len(rows), MINE_BATCH_SIZE):
        hi = min(len(rows), lo + MINE_BATCH_SIZE)
        sims = q_embs[lo:hi] @ catalog_embs.T

        for j, (bid, q) in enumerate(rows[lo:hi]):
            s = sims[j]
            pos_sim = float(s[bidx[bid]])

            # Get top-K candidates
            order = np.argpartition(-s, TOP_K)[:TOP_K]
            order = order[np.argsort(-s[order])]

            banned = {bid} | query_positives.get(norm(q), set())
            cands = []
            for idx in order:
                cid = all_book_ids[idx]
                cscore = float(s[idx])
                if cluster_of.get(cid) == cluster_of.get(bid):
                    continue
                if cid in banned:
                    continue
                cands.append((cid, cscore))

            # Select negatives from ranked candidates (skip top ranks)
            negs = []
            for rank, (cid, cscore) in enumerate(cands):
                if rank < 2:
                    continue
                if len(negs) >= N_NEG:
                    break

                is_false, reason = is_false_negative(bid, cid, cscore, meta, banned)
                if is_false:
                    blocked[reason] += 1
                    continue
                negs.append(cid)

            # Compute rank of positive
            pos_rank = int((s > pos_sim).sum())
            sp = split_of(bid)
            stats[sp]["n"] += 1
            for k in (1, 5, 10, 50):
                stats[sp][f"r@{k}"] += pos_rank < k

            outs[sp].write(json.dumps({
                "query": q,
                "positive_id": bid,
                "positive_title": meta["title_of"].get(bid, ""),
                "positive_rank": pos_rank,
                "negative_ids": negs,
                "negative_titles": [meta["title_of"].get(n, "") for n in negs],
            }, ensure_ascii=False) + "\n")

        if hi % 20000 == 0 or hi == len(rows):
            print(f"  Mined {hi:,}/{len(rows):,}")

    for f in outs.values():
        f.close()

    # Print results
    print("\n  False-negative blocks breakdown:")
    for reason, count in blocked.most_common():
        print(f"    {reason:25}: {count:,}")

    print("\n  Split Results (pre-trained model retrieval baseline):")
    for sp in ("train", "val", "test"):
        st = stats[sp]
        n_ = st["n"] or 1
        print(f"    {sp}: {st['n']:,} pairs | R@1={st['r@1']/n_:.3f} "
              f"R@5={st['r@5']/n_:.3f} R@10={st['r@10']/n_:.3f} "
              f"R@50={st['r@50']/n_:.3f}")


