# NLP helpers
WORD_RE = re.compile(r"\b[a-zA-Z']+\b")
STOPWORDS = {
    "a", "an", "the", "and", "or", "of", "in", "on", "for", "to", "with",
    "about", "is", "are", "that", "this", "i", "my", "me", "book", "books",
    "novel", "novels", "story", "stories", "looking", "read", "reading",
    "series", "vol", "volume", "part",
}


def norm(q):
    return re.sub(r"\s+", " ", q.lower().strip())


def words(text):
    return WORD_RE.findall((text or "").lower())


def content_words(text):
    return [w for w in words(text) if len(w) >= 3 and w not in STOPWORDS]


def extract_base_title(title):
    """Strips subtitles, edition notes, parentheses, and brackets."""
    t = re.sub(r"\(.*?\)", "", title)
    t = re.sub(r"\[.*?\]", "", t)
    t = re.split(r"[:\-–—;]", t)[0]
    return norm(t)


def get_significant_words(title):
    ws = re.findall(r"[a-z0-9']+", norm(title))
    return {w for w in ws if len(w) >= 3 and w not in STOPWORDS}


def extract_series_name(title):
    """Extracts series identifier from title using regex heuristics."""
    m = re.search(
        r"\(([^,#\)]+)(?:,|\s+#|\s+Book|\s+Vol|\s+Part|\s+Novella|\s+Series|\s+Trilogy)",
        title, re.IGNORECASE
    )
    if m:
        s = norm(m.group(1))
        if len(s) >= 3 and s not in STOPWORDS:
            return s
    m = re.search(
        r":\s+A\s+([^\:\(\)]+?)\s+(?:Novel|Series|Novella|Trilogy|Chronicles)",
        title, re.IGNORECASE
    )
    if m:
        s = norm(m.group(1))
        if len(s) >= 3 and s not in STOPWORDS:
            return s
    return ""


