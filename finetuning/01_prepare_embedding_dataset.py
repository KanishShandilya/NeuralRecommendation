# Main
# ==============================================================================
def main():
    parser = argparse.ArgumentParser(description="Prepare embedding fine-tuning dataset")
    parser.add_argument("--model", default=DEFAULT_MODEL,
                        help="HuggingFace model ID or local path for mining embeddings")
    parser.add_argument("--skip-embed", action="store_true",
                        help="Stop after audit (no GPU/model needed)")
    parser.add_argument("--pairs-file", default=str(PAIRS_FILE),
                        help="Path to book_query_pairs.jsonl")
    args = parser.parse_args()

    print("=" * 70)
    print("  EMBEDDING DATASET PREPARATION PIPELINE")
    print(f"  Mining Model: {args.model}")
    print("=" * 70)

    # Load query-book pairs
    pairs_path = Path(args.pairs_file)
    if not pairs_path.exists():
        print(f"ERROR: {pairs_path} not found!")
        print("Please provide book_query_pairs.jsonl with format:")
        print('  {"book_id": "123", "title": "...", "queries": ["q1", "q2", "q3", "q4", "q5"]}')
        return

    records = [json.loads(l) for l in open(pairs_path, encoding="utf-8") if l.strip()]
    print(f"\n  Loaded {len(records):,} books from {pairs_path.name}")

    # Step 1: Audit
    audit_dataset(records)

    if args.skip_embed:
        print("\n  --skip-embed flag set. Stopping after audit.")
        return

    # Step 2: Load metadata
    if not DB_FILE.exists():
        print(f"\nERROR: {DB_FILE} not found!")
        return
    meta = load_metadata_from_db(DB_FILE)

    # Step 3: Build work clusters and split
    clusters, cluster_of = build_work_clusters(records, meta)
    train_keys, val_keys, test_keys = split_by_clusters(clusters)

    book_ids_in_meta = [str(r["book_id"]) for r in records if str(r["book_id"]) in meta["book_texts"]]
    all_book_ids = sorted(set(book_ids_in_meta))
    print(f"  Books with metadata: {len(all_book_ids):,}/{len(records):,}")

    # Step 4: Load model and embed catalog
    import torch
    from sentence_transformers import SentenceTransformer

    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"\n[Model] Loading {args.model} on {device}...")
    model = SentenceTransformer(args.model, device=device)

    catalog_embs = embed_catalog(model, meta, all_book_ids)

    # Step 5: Mine hard negatives and write splits
    mine_hard_negatives(
        records, meta, all_book_ids, catalog_embs, model,
        cluster_of, train_keys, val_keys, test_keys,
    )

    # Summary
    for split in ("train", "val", "test"):
        path = BASE_DIR / f"{split}.jsonl"
        if path.exists():
            n_lines = sum(1 for _ in open(path))
            mb = path.stat().st_size / (1024**2)
            print(f"  {split}.jsonl: {n_lines:,} rows ({mb:.1f} MB)")

    print("\n" + "=" * 70)
    print("  DATASET PREPARATION COMPLETE")
    print("=" * 70)


if __name__ == "__main__":
    main()
