"""
01 — Prepare Embedding Fine-Tuning Dataset
============================================
Prepares training, validation, and test splits with hard-negative mining
for fine-tuning a bi-encoder embedding model (e.g., BAAI/bge-small-en-v1.5).

Inputs Required:
  - book_query_pairs.jsonl:  {book_id, title, queries[5]} generated by Qwen 3 8B
  - books_metadata.sqlite3:  SQLite DB with columns (book_id, title, authors, description, popular_shelves)
  - goodreads_books.json.gz: (Optional) Raw UCSD Goodreads dump for metadata enrichment

Pipeline:
  1. Load & audit synthetic query dataset (structural/diversity/leakage checks)
  2. Load book metadata from SQLite and format document text
  3. Split by work clusters (80% train / 10% val / 10% test) — edition-safe
  4. Embed full catalog with a pre-trained model for hard-negative mining
  5. Mine 5 hard negatives per query with multi-layer false-negative protection
  6. Output: train.jsonl, val.jsonl, test.jsonl

Usage:
  python 01_prepare_embedding_dataset.py
  python 01_prepare_embedding_dataset.py --skip-embed   # audit + split only (no GPU needed)
  python 01_prepare_embedding_dataset.py --model BAAI/bge-small-en-v1.5  # specify mining model
"""

