# Step 1: Audit Dataset Quality
# ==============================================================================
def tfidf_max_similarity(queries):
    """Compute max pairwise TF-IDF cosine similarity among sibling queries."""
    docs = [set(content_words(q)) for q in queries]
    n = len(docs)
    if n < 2:
        return 0.0
    df = Counter(w for d in docs for w in d)
    idf = {w: math.log((n + 1) / (c + 1)) + 1 for w, c in df.items()}
    vecs = []
    for q in queries:
        tf = Counter(content_words(q))
        vecs.append({w: c * idf[w] for w, c in tf.items()})

    def cos(a, b):
        dot = sum(v * b.get(w, 0) for w, v in a.items())
        na = math.sqrt(sum(v * v for v in a.values()))
        nb = math.sqrt(sum(v * v for v in b.values()))
        return dot / (na * nb) if na and nb else 0.0

    return max(cos(vecs[i], vecs[j]) for i in range(n) for j in range(i + 1, n))


def title_leakage(title, query):
    """Check if query contains ≥ 80% of the book's significant title words."""
    tw = set(w for w in words(title) if len(w) >= 3 and w not in STOPWORDS)
    if len(tw) < 2:
        return False
    return len(tw & set(words(query))) >= int(len(tw) * 0.8)


def audit_dataset(records):
    """Run structural, diversity, and leakage checks → dataset_quality_review.csv"""
    print("\n" + "=" * 70)
    print("  STEP 1: DATASET QUALITY AUDIT")
    print("=" * 70)

    book_ids = [r["book_id"] for r in records]
    q_counts = Counter(len(r.get("queries", [])) for r in records)
    all_q = [q for r in records for q in r["queries"]]
    wc = sorted(len(q.split()) for q in all_q)

    print(f"  Books: {len(records):,}  |  Unique IDs: {len(set(book_ids)):,}")
    print(f"  Queries/book distribution: {dict(sorted(q_counts.items()))}")
    print(f"  Total queries: {len(all_q):,}")
    print(f"  Empty queries: {sum(1 for q in all_q if not q.strip())}")
    print(f"  Word count: min={wc[0]} median={wc[len(wc)//2]} "
          f"p95={wc[int(len(wc)*.95)]} max={wc[-1]}")

    # Cross-book duplicate detection
    nq = Counter(norm(q) for q in all_q)
    dups = {n for n, c in nq.items() if c > 1}
    print(f"  Cross-book duplicate queries: {sum(nq[n] for n in dups):,} rows "
          f"({len(dups):,} unique)")

    # Within-book duplicate detection
    within = sum(1 for r in records if len(set(norm(q) for q in r["queries"])) < 5)
    print(f"  Within-book duplicate books: {within}")

    # Diversity analysis
    sims = sorted(tfidf_max_similarity(r["queries"]) for r in records)
    print(f"  5-query TF-IDF max similarity: median={sims[len(sims)//2]:.3f} "
          f"p95={sims[int(len(sims)*.95)]:.3f} "
          f"| books > 0.85: {sum(1 for s in sims if s > 0.85)}")

    # Word count by query position
    print("  Word count by query position (broad → specific):")
    for i in range(min(5, min(len(r["queries"]) for r in records))):
        lens = sorted(len(r["queries"][i].split()) for r in records)
        print(f"    pos{i+1}: mean={sum(lens)/len(lens):.1f} median={lens[len(lens)//2]}")

    # Flag suspicious queries
    suspicious = []
    for r in records:
        for i, q in enumerate(r["queries"], 1):
            w = len(q.split())
            flags = (
                (["too_short"] if w < 3 else []) +
                (["too_long"] if w > 40 else []) +
                (["title_leak"] if title_leakage(r["title"], q) else [])
            )
            if flags:
                suspicious.append({
                    "book_id": r["book_id"],
                    "title": r["title"],
                    "query_number": i,
                    "query": q,
                    "word_count": w,
                    "flags": "|".join(flags),
                })

    if suspicious:
        with open(AUDIT_FILE, "w", newline="", encoding="utf-8") as f:
            wtr = csv.DictWriter(f, fieldnames=list(suspicious[0]))
            wtr.writeheader()
            wtr.writerows(suspicious)
        print(f"  Suspicious rows → {AUDIT_FILE.name} ({len(suspicious):,})")
    else:
        print("  No suspicious rows found.")


